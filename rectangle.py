def area(a, b):
    '''
    Возвращает площадь прямоугольника.

        Параметры:
            a (int или float): длина прямоугольника
            b (int или float): ширина прямоугольника
            
        Возвращаемое значение:
            area (int или float): площадь прямоугольника, произведение a на b.
    '''
    return a * b

def perimeter(a, b):
    '''
    Возвращает периметр прямоугольника.
    
        Параметры:
            a (int или float): длина прямоугольника
            b (int или float): ширина прямоугольника
            
        Возвращаемое значение:
            perimeter (int или float): периметр прямоугольника, удвоенная сумма a и b.
    '''
    return 2*(a + b)