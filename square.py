
def area(a):
    '''
    Возвращает площадь квадрата.
    
        Параметры:
            a (int или float): сторона квадрата
            
        Возвращаемое значение: area (int или float): площадь квадрата, произвеение a на a
    '''
    return a * a


def perimeter(a):
    '''
    Возвращает периметр квадрата.
    
        Параметры:
            a (int или float): сторона квадрата
            
        Возвращаемое значение:
            perimeter (int или float): периметр квадрата, произведение 4 на a
    '''
    return 4 * a
