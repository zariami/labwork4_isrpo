def area(a, h):
    ''' 
    Возвращает площадь треугольника.

        Параметры:
            a (int или float): основание треугольника
            b (int или float): высота треугольника

        Возвращаемое значение:
            area (int или float): площадь треугольника, произведение a на b, поделённое на 2.
    '''        
    return a * h / 2

def perimeter(a, b, c):
    '''
    Возвращает периметр треугольника.

        Параметры:
            a (int или float): первая сторона треугольника
            b (int или float): вторая сторона треугольника
            c (int или float): третья сторона треугольника
            
        Возвращаемое значение:
            perimeter (int или float): периметр треугольника, сумма a, b и с
    '''
    return a + b + c
