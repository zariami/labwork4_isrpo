import math


def area(r):
    '''
    Возвращает площадь круга.
    
        Параметры:
            r (int или float): радиус круга
            
        Возвращаемое значение:
            area (float): площадь круга, произведение чисоа пи на r на r.
    '''
    return math.pi * r * r


def perimeter(r):
    '''
    Возвращает длину окружности.
    
        Параметры:
            r (int или float): радиус круга
            
        Возвращаемое значение:
            perimeter (float): длина окружности, удвоенное произведение числа пи на r.
    '''
    return 2 * math.pi * r

